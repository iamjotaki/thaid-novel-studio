def clean_chapter_subtitle(subtitle: str, chapter_num: int = None, book_title: str = None) -> str:
    """
    ทำความสะอาดชื่อตอน (Subtitle) ให้สละสลวย กระชับ และไม่มีคำว่า 'ตอนที่ xx' ต่อท้ายเด็ดขาด
    - ตัดคำต่อท้าย เช่น (ตอนที่ 21), [ตอนที่ 21], ตอนที่ 21, (บทที่ 21)
    - ตัดคำนำหน้า เช่น บทที่ 1:, ตอนที่ 1:
    - ตัดวงเล็บชื่อเรื่อง เช่น (หย่าให้ไว เพราะฉันไม่ใช่...)
    - ทำความสะอาดอักขระแปลกปลอมด้วย sanitize_thai_text()
    """
    if not subtitle:
        if chapter_num is not None:
            return FALLBACK_NARRATIVE_BEATS[(chapter_num - 1) % len(FALLBACK_NARRATIVE_BEATS)]
        return ""

    s = sanitize_thai_text(str(subtitle))

    # 1. Strip trailing (ตอนที่ xx), [ตอนที่ xx], (บทที่ xx), etc.
    s = re.sub(r'\s*[\(\[\{]\s*(?:ตอนที่|บทที่|ตอน|บท|ch\.?|ep\.?|chapter)\s*\d+\s*[\)\]\}]\s*$', '', s, flags=re.IGNORECASE)
    # 2. Strip trailing ตอนที่ xx, บทที่ xx
    s = re.sub(r'\s*(?:ตอนที่|บทที่|ตอน|บท|ch\.?|ep\.?|chapter)\s*\d+\s*$', '', s, flags=re.IGNORECASE)
    # 3. Strip leading บทที่ xx: or ตอนที่ xx:
    s = re.sub(r'^\s*(?:บทที่|ตอนที่|ตอน|บท|chapter|ep\.?)\s*\d+\s*[:\-\.]\s*', '', s, flags=re.IGNORECASE)
    # 4. Strip trailing book title in parentheses e.g. (หย่าให้ไว...)
    if book_title:
        clean_bt = re.escape(re.sub(r"[\(\)\[\]\{\}\<\>\"\'\#]", "", book_title).strip())
        if clean_bt:
            s = re.sub(rf'\s*\({clean_bt}\)\s*$', '', s)
    s = re.sub(r'\s*\([^)]*(?:หย่า|รัก|แค้น|ใจ|เธอ|คุณ|ประธาน|มาเฟีย|ฮูหยิน)[^)]*\)\s*$', '', s)
    s = s.strip(' :-–—_')

    # 5. If string was merely "ตอนที่ 2" or empty, assign a dynamic narrative beat
    if not s or re.match(r'^(?:ตอนที่|บทที่|ตอน|บท|chapter|ep\.?)\s*\d*$', s, flags=re.IGNORECASE):
        if chapter_num is not None:
            return FALLBACK_NARRATIVE_BEATS[(chapter_num - 1) % len(FALLBACK_NARRATIVE_BEATS)]
        return ""

    return s

