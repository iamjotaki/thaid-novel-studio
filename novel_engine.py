def count_thai_words(text):
    """นับจำนวนคำภาษาไทยด้วย pythainlp หรือ fallback การประมาณคำ"""
    if not text:
        return 0
    if HAS_PYTHAINLP:
        tokens = [t for t in word_tokenize(text, engine='newmm') if t.strip()]
        return len(tokens)
    thai_chars = len(text.replace(" ", "").replace("\n", ""))
    return max(1, round(thai_chars / 4.5))

