def classify_story_genre(genre="", title="", synopsis="", category=""):
    """
    วิเคราะห์แก่นแท้ของแนวเรื่องอย่างแม่นยำ 100% จาก genre, title, synopsis, และ category
    แก้ปัญหา Web Novel Trope เช่น 'ฮูหยิน / ทะลุมิติ / ผัวโบ้' หลุดไปเป็นไทยโมเดิร์น
    """
    combined = f"{genre} {title} {synopsis} {category}".lower()

    # 1. Chinese Historical / Period / Wuxia / Xianxia
    chinese_keywords = [
        "จีน", "chinese", "13_chinese", "59", "ฮูหยิน", "ท่านอ๋อง", "ชินอ๋อง", "อ๋อง",
        "แม่ทัพ", "ฮ่องเต้", "ฮองเฮา", "วังหลวง", "ราชสำนัก", "สนม", "พระสนม", "พระชายา",
        "ตำลึง", "อนุภรรยา", "อนุ", "ขันที", "กระบี่", "ลมปราณ", "ย้อนยุค", "ข้ามภพ",
        "ยุคโบราณ", "โบราณ", "องค์หญิง", "องค์ชาย", "จวน", "แพทย์หญิงยุคปัจจุบัน", "โอสถ",
        "หมอเทวดา", "เจ้าก้อนแป้ง", "ยุทธภพ", "เซียน", "สำนัก", "บำเพ็ญ", "กำลังภายใน",
        "วิญญาณยุทธ์", "คัมภีร์", "แดนเซียน", "พรรคมาร", "วิวาห์พระราชทาน", "ราชโองการ"
    ]
    if any(k in combined for k in chinese_keywords):
        return "chinese"

    # 2. Boy Love (Yaoi / BL)
    bl_keywords = ["วาย", "boy love", "bl", "ชาย-ชาย", "yaoi", "32", "นายเอก", "omegaverse", "อัลฟ่า", "โอเมก้า"]
    if any(k in combined for k in bl_keywords):
        return "boy_love"

    # 3. Girl Love (Yuri / GL)
    gl_keywords = ["ยูริ", "girl love", "gl", "หญิง-หญิง", "yuri", "33"]
    if any(k in combined for k in gl_keywords):
        return "girl_love"

    # 4. Fantasy / Sci-Fi / Game System
    fantasy_keywords = ["แฟนตาซี", "fantasy", "ต่างโลก", "58", "ดันเจี้ยน", "ฮันเตอร์", "มอนสเตอร์", "ระบบเกม", "เวทมนตร์", "จอมเวท", "ไซไฟ", "หุ่นรบ", "ต่างมิติ"]
    if any(k in combined for k in fantasy_keywords):
        return "fantasy"

    # 5. Mystery / Thriller
    mystery_keywords = ["สืบสวน", "ลึกลับ", "ระทึกขวัญ", "mystery", "thriller", "16", "คดีฆาตกรรม", "ชันสูตร", "นิติเวช"]
    if any(k in combined for k in mystery_keywords):
        return "mystery"

    # Default: Thai Contemporary Romance
    return "thai_romance"

