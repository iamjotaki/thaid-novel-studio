def ruthless_trim_ending(text):
    """
    ตัดประโยคสปอยล์ / สรุปคาดเดาอนาคต / ชี้นำเนื้อเรื่องตอนท้าย (Hard Cut Cliffhanger):
    - ตรวจจับและหั่นครึ่งหลังของประโยคที่มี 'โดยไม่มีใครล่วงรู้เลยว่า...', 'หารู้ไม่ว่า...', 'โดยที่เขาไม่รู้เลยว่า...', 'และนั่นคือจุดเริ่มต้นของ...' ทิ้งทันที
    - บังคับให้ตัดจบห้วนๆ ที่การกระทำ (Action) หรือบทสนทนา (Dialogue) สุดท้าย
    - หากย่อหน้าสุดท้ายเป็นเพียงการบรรยายสรุปศีลธรรม/คาดเดาอนาคต ให้ตัดทิ้งทั้งย่อหน้า เพื่อให้จบที่ฉากคุยหรือแอ็กชันก่อนหน้า
    เสมือนงานเขียนของนักเขียนมืออาชีพ
    """
    if not text:
        return text

    content = text.rstrip()
    paragraphs = [p.strip() for p in content.split("\n\n") if p.strip()]
    if not paragraphs:
        return content

    # 1. Regex จับ clause สปอยล์/คาดเดาอนาคตท้ายประโยค
    spoiler_clause_pattern = re.compile(
        r"[\s,،]*(โดย(ไม่มีใคร|ที่\S*|ไม่)?(ล่วง)?รู้(เลย)?ว่า"
        r"|หารู้ไม่(ว่า)?"
        r"|โดยหารู้ไม่(ว่า)?"
        r"|แต่(ใครเล่าจะ|ไม่มีใคร)(ล่วง)?รู้(เลย)?ว่า"
        r"|ทว่า(ไม่มีใคร|ใครจะ|เขา|เธอ)(ล่วง)?รู้(เลย)?ว่า"
        r"|และนั่น(ก็)?คือ(จุดเริ่มต้น|ปฐมบท)"
        r"|ทิ้งไว้เพียง(ความเงียบ|บทเรียน|รอยแผล)"
        r"|โดยไม่รู้(เลย)?แม้แต่น้อยว่า"
        r"|โดยที่หารู้ไม่ว่า"
        r"|ก่อนที่พายุลูกใหญ่จะ"
        r"|ท่ามกลางพายุ(อารมณ์)?ที่กำลังจะ).*$",
        re.DOTALL
    )

    # 2. ตรวจสอบย่อหน้าสุดท้าย หากเป็นย่อหน้าสรุปคาดเดาอนาคตหรือสั่งสอนศีลธรรม (standalone preachy paragraph)
    moral_cues = [
        "โดยไม่มีใคร", "หารู้ไม่", "และนี่คือ", "และนั่นคือ", "บทเรียนสำคัญ",
        "ไม่ว่าพรุ่งนี้", "ไม่ว่าหนทางข้างหน้า", "ความหวังครั้งใหม่", "บททดสอบที่แท้จริง",
        "จุดเริ่มต้นของหายนะ", "สายตาคู่หนึ่งกำลังจับจ้อง"
    ]
    if len(paragraphs) > 1:
        last_para = paragraphs[-1]
        if len(last_para) < 260 and any(cue in last_para for cue in moral_cues):
            paragraphs.pop()

    # 3. หั่นครึ่งหลังของประโยคที่มี clause สปอยล์ในย่อหน้าสุดท้าย
    if paragraphs:
        last_para = paragraphs[-1]
        m = spoiler_clause_pattern.search(last_para)
        if m:
            trimmed = last_para[:m.start()].rstrip(" ,،-—\t\r\n")
            # ถ้าส่วนที่เหลือมีความยาวพอสมควรหรือมีบทพูด ให้ตัดจบตรงนี้ทันที
            if len(trimmed) >= 10:
                paragraphs[-1] = trimmed
            elif len(paragraphs) > 1:
                paragraphs.pop()

    clean_res = "\n\n".join(paragraphs).strip()
    return clean_res

def de_ai_linter(text):
    """
    Programmatic Post-Processing & Style Linter:
    1. ตรวจจับคำและวลีสไตล์ AI ซ้ำซาก (AI Cliché Dictionary)
    2. ตัดคำฟุ่มเฟือยและคลีนสำนวน De-AI อัตโนมัติ
    3. ตรวจสอบการตัดจบตอน (Hard Cut Cliffhanger) และหั่นประโยคสปอยล์/คาดเดาอนาคตตอนท้ายทิ้งทันที
    """
    if not text:
        return {"text": "", "detected": [], "score": 100, "total_cliches": 0}

    detected = []
    clean_text = text

    for pattern in AI_CLICHE_PATTERNS:
        matches = re.findall(pattern, clean_text)
        if matches:
            detected.append({"pattern": pattern, "count": len(matches)})
            if "อดไม่ได้ที่จะ" in pattern:
                clean_text = re.sub(r"อดไม่ได้ที่จะ\s*", "", clean_text)
            elif "ทว่าในใจกลับ" in pattern:
                clean_text = re.sub(r"ทว่าในใจกลับ\s*", "แต่ในใจ", clean_text)
            elif "ความเงียบ" in pattern:
                clean_text = re.sub(r"ความเงียบ(งัน)?เข้า(ปกคลุม|ครอบงำ)", "รอบตัวเงียบสนิท", clean_text)
            elif "สูดลมหายใจเข้าลึก" in pattern:
                clean_text = re.sub(r"สูดลมหายใจเข้าลึก[ๆ]?", "ผ่อนลมหายใจช้าๆ", clean_text)
            elif "แววตาที่เปี่ยมด้วย" in pattern:
                clean_text = re.sub(r"แววตาที่เปี่ยมด้วย(\S+)", r"แววตา\1", clean_text)
            elif "ลึกๆ ในก้นบึ้ง" in pattern:
                clean_text = re.sub(r"ลึกๆ ในก้นบึ้ง", "ลึกในใจ", clean_text)
            elif "ความรู้สึกแปลกประหลาด" in pattern:
                clean_text = re.sub(r"ความรู้สึกแปลกประหลาด", "ความรู้สึกที่คลุมเครือ", clean_text)
            elif "ท่วมท้น" in pattern:
                clean_text = re.sub(r"ท่วมท้น(ไป)?ด้วย(\S+)", r"ล้นหลามด้วย\2", clean_text)
            elif "ประกายบางอย่างในดวงตา" in pattern:
                clean_text = re.sub(r"ประกายบางอย่างในดวงตา", "แววตาวูบไหว", clean_text)
            elif "ราวกับเวลาหยุดหมุน" in pattern:
                clean_text = re.sub(r"ราวกับเวลาหยุดหมุน", "ทุกอย่างรอบตัวชะงักงัน", clean_text)

    # Programmatic Hard Cut Cliffhanger: หั่นครึ่งหลังของประโยคสปอยล์ท้ายบททิ้งทันที
    clean_text = ruthless_trim_ending(clean_text)

    total_found = sum(d["count"] for d in detected)
    score = max(0, 100 - (total_found * 10))
    return {
        "text": clean_text.strip(),
        "detected": detected,
        "total_cliches": total_found,
        "score": score
    }

