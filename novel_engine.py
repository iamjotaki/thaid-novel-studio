    def _format_3d_character_sheet(self, context_memory):
        """จัดรูปแบบ Character Sheet 3 มิติ (Want, Need, Flaw, Speaking Style, Hidden Agenda)"""
        if not context_memory:
            return ""
        chars = context_memory if isinstance(context_memory, list) else context_memory.get("characters", [])
        if not chars:
            return ""
        lines = ["[Character Bible & 3D Psychology (ควบคุมความคงเส้นคงวาและมิติของตัวละคร)]"]
        for c in chars:
            name = c.get("name", "")
            role = c.get("role", "")
            trait = c.get("trait") or c.get("traits", "")
            want = c.get("want", "")
            need = c.get("need", "")
            flaw = c.get("flaw", "")
            style = c.get("speaking_style", "")
            agenda = c.get("hidden_agenda", "")
            emotion = c.get("current_emotion", "")

            char_str = f"- {name} ({role}): บุคลิก: {trait}"
            if want: char_str += f" | Want (เป้าหมายภายนอก): {want}"
            if need: char_str += f" | Need (สิ่งที่ขาดในใจ): {need}"
            if flaw: char_str += f" | Flaw (ปมในใจ/จุดอ่อน): {flaw}"
            if style: char_str += f" | Speaking Style (น้ำเสียง/คำติดปาก): {style}"
            if agenda: char_str += f" | Hidden Agenda (สิ่งที่คิดแต่ไม่พูด): {agenda}"
            if emotion: char_str += f" | Current Emotion: {emotion}"
            lines.append(char_str)
        return "\n".join(lines)

