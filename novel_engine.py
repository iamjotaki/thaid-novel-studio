    def _call_gemini_sdk(self, prompt, max_tokens=8192, temperature=0.85):
        """
        เรียกใช้ Google GenAI SDK พร้อมระบบ Multi-Key Failover และ Model Cascade ตามแบบ C:/NV
        """
        if not self.api_keys or not HAS_GOOGLE_GENAI:
            return None

        safety = [
            types.SafetySetting(category=types.HarmCategory.HARM_CATEGORY_HARASSMENT, threshold=types.HarmBlockThreshold.BLOCK_NONE),
            types.SafetySetting(category=types.HarmCategory.HARM_CATEGORY_HATE_SPEECH, threshold=types.HarmBlockThreshold.BLOCK_NONE),
            types.SafetySetting(category=types.HarmCategory.HARM_CATEGORY_SEXUALLY_EXPLICIT, threshold=types.HarmBlockThreshold.BLOCK_NONE),
            types.SafetySetting(category=types.HarmCategory.HARM_CATEGORY_DANGEROUS_CONTENT, threshold=types.HarmBlockThreshold.BLOCK_NONE),
        ]
        config = types.GenerateContentConfig(
            safety_settings=safety,
            max_output_tokens=max_tokens,
            temperature=temperature
        )

        for current_key in self.api_keys:
            client = genai.Client(api_key=current_key)
            key_tag = f"...{current_key[-4:]}" if len(current_key) >= 4 else "key"

            for model_name in self.preferred_models:
                try:
                    resp = client.models.generate_content(
                        model=model_name,
                        contents=prompt,
                        config=config
                    )
                    # Check parts directly from candidates to avoid SDK thought_signature warnings
                    if resp and resp.candidates:
                        c = resp.candidates[0]
                        if c.content and c.content.parts:
                            parts = [p.text for p in c.content.parts if hasattr(p, 'text') and p.text]
                            if parts:
                                self.last_used_key = current_key
                                return "".join(parts).strip()
                    if resp and resp.text and resp.text.strip():
                        self.last_used_key = current_key
                        return resp.text.strip()
                except Exception as e:
                    err_msg = str(e)
                    print(f"[NovelEngine] Key [{key_tag}] with Model {model_name} failed: {e}")
                    # If quota or rate limit exceeded on this key
                    if "RESOURCE_EXHAUSTED" in err_msg or "429" in err_msg:
                        if len(self.api_keys) > 1:
                            print(f"[NovelEngine] Quota/Rate limit reached on Key [{key_tag}], switching to next available key...")
                            break
                        else:
                            print(f"[NovelEngine] Rate limit on single key [{key_tag}], backing off 6s before retry...")
                            time.sleep(6)
                            try:
                                resp = client.models.generate_content(
                                    model=model_name,
                                    contents=prompt,
                                    config=config
                                )
                                if resp and resp.text and resp.text.strip():
                                    self.last_used_key = current_key
                                    return resp.text.strip()
                            except Exception as retry_err:
                                print(f"[NovelEngine] Backoff retry failed: {retry_err}")
                                break
                    continue
        return None

